  const pick = (arr, salt) => arr[(h >>> salt) % arr.length];
  return {
    skin: pick(AV_SKINS, 0),
    hair: pick(AV_HAIRS, 3),
    robe: pick(AV_ROBES, 6),
    hairD: pick(AV_HAIRD, 9),
    beardD: pick(AV_BEARDD, 12)
  };
